# ── EXIF / XMP helpers ────────────────────────────────────────────────────────

_DJI_NS = "http://www.dji.com/drone-dji/1.0/"
_RDF_NS = "http://www.w3.org/1999/02/22-rdf-syntax-ns#"


def _dji_xmp(xmp_bytes: bytes) -> dict[str, str]:
    """Return a flat dict of every dji: attribute from the XMP block."""
    try:
        root = ET.fromstring(xmp_bytes)
    except ET.ParseError:
        return {}
    out: dict[str, str] = {}
    for el in root.iter():
        for attr, val in el.attrib.items():
            if attr.startswith(f"{{{_DJI_NS}}}"):
                out[attr[len(f"{{{_DJI_NS}}}"):]  ] = val
        if el.tag.startswith(f"{{{_DJI_NS}}}"):
            key = el.tag[len(f"{{{_DJI_NS}}}"):]
            if el.text:
                out[key] = el.text.strip()
    return out


def _extract_xmp(data: bytes) -> bytes | None:
    """Find and return the raw XMP block from a JPEG byte string."""
    start = data.find(b"<x:xmpmeta")
    end = data.find(b"</x:xmpmeta>")
    if start == -1 or end == -1:
        return None
    return data[start: end + len(b"</x:xmpmeta>")]


def _rational_to_float(r: tuple) -> float:
    """Convert an EXIF rational (numerator, denominator) to float."""
    num, den = r
    return num / den if den else 0.0


def _gps_to_decimal(dms: tuple, ref: str) -> float:
    """Convert GPS EXIF DMS rational tuple to signed decimal degrees."""
    deg = _rational_to_float(dms[0])
    mn = _rational_to_float(dms[1])
    sec = _rational_to_float(dms[2])
    dec = deg + mn / 60.0 + sec / 3600.0
    if ref in ("S", "W"):
        dec = -dec
    return dec


def _parse_dewarp_data(dewarp_str: str) -> dict[str, float] | None:
    """Parse a DJI DewarpData XMP string into a dict of parameters."""
    if not dewarp_str:
        return None
    try:
        parts = dewarp_str.split(';')
        if len(parts) < 2:
            return None
        vals = [float(x) for x in parts[1].split(',')]
        if len(vals) < 9:
            return None
        return {
            "fx": vals[0],
            "fy": vals[1],
            "cx": vals[2],
            "cy": vals[3],
            "k1": vals[4],
            "k2": vals[5],
            "p1": vals[6],
            "p2": vals[7],
            "k3": vals[8]
        }
    except Exception as exc:
        print(f"[dewarp] Error parsing DewarpData string '{dewarp_str}': {exc}")
        return None


def _parse_dji_metadata(jpeg_bytes: bytes) -> dict[str, Any]:
    """
    Extract all georeferencing-relevant metadata from a DJI JPEG.

    Returns a dict with keys (all floats unless noted):
      lat, lon, alt_abs, alt_rel, lrf_dist,
      gimbal_yaw, gimbal_pitch, gimbal_roll,
      focal_px, cx, cy,
      img_width, img_height  (ints)
      dewarp_flag (int), dewarp_data (str)
    Missing values default to None.
    """
    import piexif
    from PIL import Image

    result: dict[str, Any] = {}

    # --- Standard EXIF (GPS + image dimensions) ----------------------------
    try:
        exif = piexif.load(jpeg_bytes)
        gps = exif.get("GPS", {})
        if gps:
            lat_dms = gps.get(piexif.GPSIFD.GPSLatitude)
            lat_ref = gps.get(piexif.GPSIFD.GPSLatitudeRef, b"N").decode()
            lon_dms = gps.get(piexif.GPSIFD.GPSLongitude)
            lon_ref = gps.get(piexif.GPSIFD.GPSLongitudeRef, b"E").decode()
            alt_r = gps.get(piexif.GPSIFD.GPSAltitude)
            if lat_dms:
                result["lat"] = _gps_to_decimal(lat_dms, lat_ref)
            if lon_dms:
                result["lon"] = _gps_to_decimal(lon_dms, lon_ref)
            if alt_r:
                result["alt_abs"] = _rational_to_float(alt_r)
        exif0 = exif.get("0th", {})
        result["img_width"] = exif0.get(piexif.ImageIFD.ImageWidth)
        result["img_height"] = exif0.get(piexif.ImageIFD.ImageLength)
    except Exception:
        pass

    # Width/height from PIL if EXIF didn't have them
    if not result.get("img_width") or not result.get("img_height"):
        try:
            img = Image.open(io.BytesIO(jpeg_bytes))
            result["img_width"], result["img_height"] = img.size
        except Exception:
            pass

    # --- DJI XMP block ----------------------------------------------------
    xmp_bytes = _extract_xmp(jpeg_bytes)
    if xmp_bytes:
        dji = _dji_xmp(xmp_bytes)

        def _f(key: str) -> float | None:
            v = dji.get(key)
            if v is None:
                return None
            try:
                return float(v.lstrip("+"))
            except ValueError:
                return None

        result["alt_abs"] = result.get("alt_abs") or _f("AbsoluteAltitude")
        result["alt_rel"] = _f("RelativeAltitude")
        result["gimbal_yaw"] = _f("GimbalYawDegree")
        result["gimbal_pitch"] = _f("GimbalPitchDegree")
        result["gimbal_roll"] = _f("GimbalRollDegree")
        result["lrf_dist"] = _f("LRFTargetDistance")
        result["focal_px"] = _f("CalibratedFocalLength")
        result["cx"] = _f("CalibratedOpticalCenterX")
        result["cy"] = _f("CalibratedOpticalCenterY")

        # Dewarp fields
        dewarp_flag_val = _f("DewarpFlag")
        result["dewarp_flag"] = int(dewarp_flag_val) if dewarp_flag_val is not None else None
        result["dewarp_data"] = dji.get("DewarpData")

    return result


