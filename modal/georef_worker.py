def _rot_x(a: float):
    """Right-hand rotation matrix around X axis."""
    import numpy as np
    c, s = math.cos(a), math.sin(a)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]], dtype=float)


def _rot_y(a: float):
    """Right-hand rotation matrix around Y axis."""
    import numpy as np
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]], dtype=float)


def _rot_z(a: float):
    """Right-hand rotation matrix around Z axis."""
    import numpy as np
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]], dtype=float)


def _compute_footprint(
    lat: float,
    lon: float,
    agl: float,
    gimbal_yaw: float,
    gimbal_pitch: float,
    gimbal_roll: float,
    focal_px: float,
    cx: float,
    cy: float,
    width: int,
    height: int,
) -> list[tuple[float, float]]:
    """
    Return the four ground corners (lat, lon) for a DJI image using CameraTransform.

    Corners are in image order: TL, TR, BR, BL.
    """
    import cameratransform as ct
    import numpy as np

    print(f"[georef] Running CameraTransform footprint calculation:")
    print(f"[georef]   Camera center (lat, lon): {lat:.7f}, {lon:.7f}")
    print(f"[georef]   AGL altitude (RelativeAltitude): {agl:.3f} m")
    print(f"[georef]   Gimbal orientation - Yaw: {gimbal_yaw:.3f}°, Pitch: {gimbal_pitch:.3f}°, Roll: {gimbal_roll:.3f}°")
    print(f"[georef]   Camera parameters - Focal: {focal_px:.3f} px, Center cx: {cx:.3f}, cy: {cy:.3f}")
    print(f"[georef]   Image size: {width} x {height}")

    # Set up Rectilinear Projection
    proj = ct.RectilinearProjection(
        focallength_px=focal_px,
        image=(width, height)
    )
    if cx is not None:
        proj.center_x_px = cx
    if cy is not None:
        proj.center_y_px = cy

    # Set up Spatial Orientation:
    # - elevation_m is camera AGL height
    # - tilt_deg is pitch + 90 (nadir = 0)
    # - roll_deg is negated roll to match standard camera roll rotation
    # - heading_deg is yaw (0 is North)
    orientation = ct.SpatialOrientation(
        elevation_m=agl,
        tilt_deg=gimbal_pitch + 90.0,
        roll_deg=-gimbal_roll,
        heading_deg=gimbal_yaw
    )

    # Initialize Camera and position it on Earth
    cam = ct.Camera(proj, orientation)
    cam.setGPSpos(lat, lon, agl)

    # Define corners in image pixel coordinates
    pixel_corners = [
        (0, 0),
        (width, 0),
        (width, height),
        (0, height)
    ]

    # Convert pixel coordinates to geographic coordinates on ground plane (Z=0)
    ground_corners = []
    print("[georef] Corner coordinates conversion (Image -> GPS):")
    for pt in pixel_corners:
        res = cam.gpsFromImage(pt, Z=0)
        # res is [lat, lon, alt]
        ground_corners.append((res[0], res[1]))
        print(f"[georef]   Pixel {pt} -> Lat: {res[0]:.7f}, Lon: {res[1]:.7f}")

    return ground_corners


def _estimate_agl(
    meta: dict[str, Any],
    altitude_mode: str = "relative",
    altitude_offset: float = 0.0,
    specified_altitude: float = 50.0,
) -> float:
    """
    Calculate AGL altitude based on the chosen mode and offset.
    - 'relative': uses meta.get("alt_rel") + altitude_offset. Falls back to alt_abs + offset.
    - 'lrf': uses lrf_dist * sin(abs(pitch)) + altitude_offset. Falls back to 'relative' mode.
    - 'specified': uses specified_altitude.
    """
    if altitude_mode == "specified":
        return max(0.1, specified_altitude)

    if altitude_mode == "lrf":
        lrf_dist = meta.get("lrf_dist")
        gimbal_pitch = meta.get("gimbal_pitch")
        if lrf_dist is not None and lrf_dist > 0 and gimbal_pitch is not None:
            # Vertical height H = D * sin(abs(pitch))
            pitch_rad = math.radians(abs(gimbal_pitch))
            agl_lrf = lrf_dist * math.sin(pitch_rad) + altitude_offset
            print(f"[agl] Calculated LRF AGL with offset: {agl_lrf:.3f} m (LRF dist: {lrf_dist:.3f} m, pitch: {gimbal_pitch:.3f}°, offset: {altitude_offset:.3f} m)")
            if agl_lrf > 0:
                return agl_lrf

    rel = meta.get("alt_rel")
    if rel is not None and rel > 0:
        return rel + altitude_offset
    abs_alt = meta.get("alt_abs")
    if abs_alt is not None and abs_alt > 0:
        return abs_alt + altitude_offset
    return 50.0  # last-resort fallback


