@app.function(
    image=image,
    secrets=[modal.Secret.from_name("salmon")],
    timeout=300,
    memory=2048,
)
def georeference_single_image(jpeg_bytes: bytes, dewarp: bool = True) -> bytes:
    """
    Modal function to georeference a single image and return its GeoTIFF bytes.
    Useful for local debugging and CLI invocation.
    """
    import tempfile
    import os

    print(f"[worker] Starting single-image georeference (dewarp={dewarp})...")
    meta = _parse_dji_metadata(jpeg_bytes)

    lat = meta.get("lat")
    lon = meta.get("lon")
    width = meta.get("img_width")
    height = meta.get("img_height")
    gimbal_pitch = meta.get("gimbal_pitch")
    gimbal_yaw = meta.get("gimbal_yaw")
    gimbal_roll = meta.get("gimbal_roll")
    
    # Check dewarp options
    dewarp_flag = meta.get("dewarp_flag")
    dewarp_data_str = meta.get("dewarp_data")
    should_undistort = dewarp and dewarp_flag == 0 and dewarp_data_str is not None
    
    dewarp_params = None
    if should_undistort:
        dewarp_params = _parse_dewarp_data(dewarp_data_str)
        if dewarp_params:
            focal_px = dewarp_params["fx"]
            cx = width / 2.0 + dewarp_params["cx"]
            cy = height / 2.0 + dewarp_params["cy"]
            print(f"[worker] Applying dewarp parameters: fx={focal_px}, cx={cx}, cy={cy}")
        else:
            print(f"[worker] Failed to parse DewarpData: {dewarp_data_str}")
            should_undistort = False

    if not should_undistort:
        focal_px = meta.get("focal_px")
        cx = meta.get("cx")
        cy = meta.get("cy")
        print(f"[worker] Using EXIF calibration fallback: focal={focal_px}, cx={cx}, cy={cy}")

    print(f"[worker] Metadata values: lat={lat}, lon={lon}, width={width}, height={height}, yaw={gimbal_yaw}, pitch={gimbal_pitch}, roll={gimbal_roll}")

    if any(v is None for v in [lat, lon, width, height, gimbal_yaw, gimbal_pitch, gimbal_roll, focal_px]):
        raise ValueError(f"Missing required georeferencing metadata: {meta}")

    if cx is None:
        cx = width / 2.0
    if cy is None:
        cy = height / 2.0

    agl = _estimate_agl(meta)
    print(f"[worker] AGL Altitude estimated: {agl:.3f} m")

    corners = _compute_footprint(
        lat, lon, agl,
        gimbal_yaw, gimbal_pitch, gimbal_roll,
        focal_px, cx, cy, width, height,
    )

    with tempfile.TemporaryDirectory() as tmpdir:
        out_path = os.path.join(tmpdir, "output.tif")
        print(f"[worker] Warping image to GeoTIFF at {out_path} (dewarp={dewarp_params is not None})...")
        _warp_to_geotiff(jpeg_bytes, corners, width, height, out_path, dewarp_params=dewarp_params)

        with open(out_path, "rb") as fh:
            geotiff_bytes = fh.read()

    print(f"[worker] Finished. GeoTIFF size: {len(geotiff_bytes)} bytes")
    return geotiff_bytes


@app.local_entrypoint()
def test_georef(
    img_path: str = None,
    dir_path: str = None,
    dewarp: bool = True,
):
    """
    Local entrypoint run via `modal run modal/georef_worker.py`.
    Sends a local image or directory of images to Modal for georeferencing.

    Examples:
      Single image:
        modal run modal/georef_worker.py --img-path DJI_20260612171254_0242_V.JPG
      Entire folder:
        modal run modal/georef_worker.py --dir-path path/to/images
      Specify whether to dewarp with: --dewarp or --no-dewarp
    """
    import os
    import glob

    if not img_path and not dir_path:
        # Default fallback to the default test image if nothing is specified
        img_path = "DJI_20260612171254_0242_V.JPG"

    if img_path:
        print(f"[local] Reading local test image from {img_path}...")
        try:
            with open(img_path, "rb") as fh:
                jpeg_bytes = fh.read()
        except FileNotFoundError:
            print(f"[local] Error: Test image {img_path} not found.")
            return

        print(f"[local] Image size: {len(jpeg_bytes)} bytes. Calling georeference_single_image on Modal (dewarp={dewarp})...")
        try:
            geotiff_bytes = georeference_single_image.remote(jpeg_bytes, dewarp=dewarp)
        except Exception as exc:
            print(f"[local] Modal function execution failed: {exc}")
            return

        base_name, _ = os.path.splitext(os.path.basename(img_path))
        suffix = "" if dewarp else "_warped"
        out_path = f"{base_name}{suffix}_ref.tif"
        print(f"[local] Received GeoTIFF. Saving to {out_path}...")
        with open(out_path, "wb") as fh:
            fh.write(geotiff_bytes)
        print(f"[local] Success! Saved georeferenced output to {out_path} ({len(geotiff_bytes)} bytes)")

    elif dir_path:
        if not os.path.isdir(dir_path):
            print(f"[local] Error: Directory '{dir_path}' does not exist.")
            return

        # Find all images in the folder (case-insensitive glob)
        files = []
        for ext in ("*.jpg", "*.jpeg", "*.JPG", "*.JPEG", "*.png", "*.PNG"):
            files.extend(glob.glob(os.path.join(dir_path, ext)))

        if not files:
            print(f"[local] No JPEGs or PNGs found in directory '{dir_path}'.")
            return

        print(f"[local] Found {len(files)} images in '{dir_path}'. Processing sequential georeferencing...")

        # Create output directory relative to source: dir_path/ref/
        ref_dir = os.path.join(dir_path, "ref")
        os.makedirs(ref_dir, exist_ok=True)
        print(f"[local] Outputs will be saved to '{ref_dir}/'")

        for idx, file_path in enumerate(sorted(files)):
            filename = os.path.basename(file_path)
            print(f"[local] [{idx+1}/{len(files)}] Reading {filename}...")
            try:
                with open(file_path, "rb") as fh:
                    jpeg_bytes = fh.read()
            except Exception as e:
                print(f"[local] Error reading {filename}: {e} — skipping")
                continue

            print(f"[local] Calling Modal for {filename} (dewarp={dewarp})...")
            try:
                geotiff_bytes = georeference_single_image.remote(jpeg_bytes, dewarp=dewarp)
            except Exception as exc:
                print(f"[local] Failed to georeference {filename} on Modal: {exc}")
                continue

            base_name, _ = os.path.splitext(filename)
            suffix = "" if dewarp else "_warped"
            out_path = os.path.join(ref_dir, f"{base_name}{suffix}_ref.tif")
            
            with open(out_path, "wb") as fh:
                fh.write(geotiff_bytes)
            print(f"[local] Successfully saved output to {out_path}")

        print("[local] Folder processing completed successfully!")

