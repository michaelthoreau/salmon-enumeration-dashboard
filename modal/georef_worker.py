"""
Salmon enumeration — Quick Georef worker.

Runs as a parallel alternative to full ODM processing.  For each image in a
flight it reads DJI EXIF / XMP metadata, computes the ground footprint using
the calibrated camera model, creates an individual georeferenced GeoTIFF, then
merges all tiles into a single Cloud-Optimised GeoTIFF (COG) that the tile
server can stream.

Algorithm
─────────
1.  Download each JPEG from S3 into memory.
2.  Parse standard GPS EXIF *and* the DJI XMP block for:
      • Absolute GPS (WGS-84, RTK when available)
      • Relative altitude (AGL above take-off)
      • Gimbal yaw / pitch / roll  (world-frame absolute angles)
      • LRF distance (laser rangefinder) for a more accurate AGL estimate
      • Calibrated focal length (px) and principal point (cx, cy)
      • Image dimensions
3.  Compute the four ground corners using a full 3-D camera projection:
      • Build a camera-to-NED rotation matrix from the gimbal angles
        using the standard aerospace ZYX Euler convention.
      • For each corner pixel, cast a ray in camera space, rotate it into
        NED, then intersect with the flat-earth ground plane at the known
        AGL altitude.
      • Convert NED offsets to geographic latitude / longitude.
4.  Write each image as a GeoTIFF with four GCPs, then warp it to EPSG:4326
    using nearest-neighbour resampling (fast; sufficient for survey imagery).
5.  Build a GDAL VRT mosaic from all warped tiles, resolve overlaps with the
    "first image wins" strategy, then translate to a compressed COG.
6.  Upload the COG to S3 at  {output_prefix}merged.tif  and report completion.

Coordinate-system notes
───────────────────────
DJI M4D (and most Mavic / Enterprise series) encodes gimbal angles in the
world / NED frame (absolute), *not* relative to the drone body.  GimbalYaw is
the camera heading clockwise from geographic North; GimbalPitch is the tilt
from horizontal (−90 = nadir); GimbalRoll is the physical roll of the camera
body.  For the M4D's downward-looking payload, GimbalRoll ≈ ±180 indicates the
camera is mounted inverted.  The drone's own electronic stabilisation corrects
the displayed image, so the displayed image "top" points toward
(GimbalYaw + 180°) when roll ≈ ±180°, and toward GimbalYaw otherwise.

We derive the AGL altitude from the LRF (laser rangefinder) distance when it is
present and the pitch is close to nadir; otherwise we fall back to the XMP
RelativeAltitude field.

Required Modal secret  (same "salmon" group as the other workers)
──────────────────────
  AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY / AWS_REGION / S3_BUCKET_NAME
  MODAL_GEOREF_TOKEN   shared bearer token; echo the same value into
                       MODAL_GEOREF_TOKEN in your Next.js environment.

Deploy
──────
  modal deploy modal/georef_worker.py
Copy the URL into MODAL_GEOREF_WORKER_URL in your Next.js env.
"""

