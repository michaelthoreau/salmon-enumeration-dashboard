def _warp_to_geotiff(
    jpeg_bytes: bytes,
    corners: list[tuple[float, float]],
    width: int,
    height: int,
    out_path: str,
    dewarp_params: dict[str, float] = None,
) -> None:
    """
    Create a EPSG:4326 GeoTIFF at *out_path* from raw JPEG bytes.

    corners: [(lat, lon), ...] for TL, TR, BR, BL in image order.
    Uses GDAL GCPs then a polynomial warp (order=1) to preserve the
    affine footprint exactly. Uses GDAL CLI via subprocess for robustness.
    """
    import subprocess
    import tempfile
    import os

    with tempfile.TemporaryDirectory() as tmpdir:
        input_jpg = os.path.join(tmpdir, "input.jpg")
        
        # If dewarp parameters are provided, undistort using OpenCV first
        if dewarp_params:
            try:
                import cv2
                import numpy as np
                print("[warp] Undistorting image with OpenCV before warping...")
                nparr = np.frombuffer(jpeg_bytes, np.uint8)
                img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
                if img is not None:
                    fx = dewarp_params["fx"]
                    fy = dewarp_params["fy"]
                    cx_abs = width / 2.0 + dewarp_params["cx"]
                    cy_abs = height / 2.0 + dewarp_params["cy"]
                    camera_matrix = np.array([
                        [fx, 0, cx_abs],
                        [0, fy, cy_abs],
                        [0, 0, 1]
                    ], dtype=np.float32)
                    dist_coeffs = np.array([
                        dewarp_params["k1"],
                        dewarp_params["k2"],
                        dewarp_params["p1"],
                        dewarp_params["p2"],
                        dewarp_params["k3"]
                    ], dtype=np.float32)
                    undistorted_img = cv2.undistort(img, camera_matrix, dist_coeffs)
                    _, encoded_img = cv2.imencode(".jpg", undistorted_img)
                    jpeg_bytes = encoded_img.tobytes()
                    print("[warp] Image undistorted successfully.")
                else:
                    print("[warp] Warning: OpenCV failed to decode image. Proceeding with raw image.")
            except Exception as e:
                print(f"[warp] Error during undistortion: {e}. Proceeding with raw image.")

        with open(input_jpg, "wb") as f:
            f.write(jpeg_bytes)

        gcp_tif = os.path.join(tmpdir, "gcp.tif")

        # For gdal_translate, format is: -gcp pixel line easting northing
        # corners order: TL, TR, BR, BL
        # Note: easting is longitude (corners[i][1]), northing is latitude (corners[i][0]).
        cmd_translate = [
            "gdal_translate",
            "-gcp", "0", "0", f"{corners[0][1]:.12f}", f"{corners[0][0]:.12f}",
            "-gcp", str(width), "0", f"{corners[1][1]:.12f}", f"{corners[1][0]:.12f}",
            "-gcp", str(width), str(height), f"{corners[2][1]:.12f}", f"{corners[2][0]:.12f}",
            "-gcp", "0", str(height), f"{corners[3][1]:.12f}", f"{corners[3][0]:.12f}",
            "-a_srs", "EPSG:4326",
            input_jpg,
            gcp_tif
        ]

        print(f"[warp] Running: {' '.join(cmd_translate)}")
        res = subprocess.run(cmd_translate, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"[warp] gdal_translate stdout: {res.stdout}")
            print(f"[warp] gdal_translate stderr: {res.stderr}")
            raise RuntimeError(f"gdal_translate failed: {res.stderr}")

        cmd_warp = [
            "gdalwarp",
            "-dstalpha",
            "-order", "1",
            "-r", "near",
            "-t_srs", "EPSG:4326",
            "-co", "COMPRESS=DEFLATE",
            "-co", "TILED=YES",
            "-co", "BIGTIFF=IF_SAFER",
            gcp_tif,
            out_path
        ]

        print(f"[warp] Running: {' '.join(cmd_warp)}")
        res = subprocess.run(cmd_warp, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"[warp] gdalwarp stdout: {res.stdout}")
            print(f"[warp] gdalwarp stderr: {res.stderr}")
            raise RuntimeError(f"gdalwarp failed: {res.stderr}")


def _merge_to_cog(tile_paths: list[str], cog_path: str) -> None:
    """
    Merge a list of individually georeferenced GeoTIFFs into a single
    Cloud-Optimised GeoTIFF using GDAL VRT + Translate.

    Overlap strategy: first-image-wins (matches survey order).
    Uses GDAL CLI via subprocess for robustness.
    """
    import subprocess
    import tempfile
    import os

    with tempfile.TemporaryDirectory() as tmpdir:
        vrt_path = os.path.join(tmpdir, "mosaic.vrt")

        # Create the VRT
        cmd_vrt = [
            "gdalbuildvrt",
            "-resolution", "highest",
            "-srcnodata", "0",
            vrt_path
        ] + tile_paths
        print(f"[merge] Running: {' '.join(cmd_vrt)}")
        res = subprocess.run(cmd_vrt, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"[merge] gdalbuildvrt stdout: {res.stdout}")
            print(f"[merge] gdalbuildvrt stderr: {res.stderr}")
            raise RuntimeError(f"gdalbuildvrt failed: {res.stderr}")

        # Add overviews
        cmd_addo = [
            "gdaladdo",
            "-r", "nearest",
            vrt_path,
            "2", "4", "8", "16", "32"
        ]
        print(f"[merge] Running: {' '.join(cmd_addo)}")
        res = subprocess.run(cmd_addo, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"[merge] gdaladdo stdout: {res.stdout}")
            print(f"[merge] gdaladdo stderr: {res.stderr}")
            raise RuntimeError(f"gdaladdo failed: {res.stderr}")

        # Translate to COG
        cmd_translate = [
            "gdal_translate",
            vrt_path,
            cog_path,
            "-co", "COMPRESS=DEFLATE",
            "-co", "TILED=YES",
            "-co", "BLOCKXSIZE=512",
            "-co", "BLOCKYSIZE=512",
            "-co", "BIGTIFF=IF_SAFER",
            "-co", "COPY_SRC_OVERVIEWS=YES"
        ]
        print(f"[merge] Running: {' '.join(cmd_translate)}")
        res = subprocess.run(cmd_translate, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"[merge] gdal_translate VRT->COG stdout: {res.stdout}")
            print(f"[merge] gdal_translate VRT->COG stderr: {res.stderr}")
            raise RuntimeError(f"gdal_translate VRT->COG failed: {res.stderr}")


# ── Main processing function ──────────────────────────────────────────────────

async def _process_images(
    task_id: str,
    images: list[ImageSpec],
    bucket: str,
    output_prefix: str,
    dewarp: bool = True,
) -> None:
    """Background task: georef each image, merge, upload COG to S3."""
    import boto3
    import numpy as np

    print(f"[process] starting task_id={task_id} total={len(images)} bucket={bucket} prefix={output_prefix} dewarp={dewarp}")
    state = _tasks[task_id]
    s3 = boto3.client(
        region_name=os.environ["AWS_REGION"],
        aws_access_key_id=os.environ["AWS_ACCESS_KEY_ID"],
        aws_secret_access_key=os.environ["AWS_SECRET_ACCESS_KEY"],
    )
    loop = asyncio.get_event_loop()

    with tempfile.TemporaryDirectory() as tmpdir:
        tile_paths: list[str] = []
        errors: list[str] = []

        for idx, img_spec in enumerate(images):
            try:
                # Download from S3
                buf = io.BytesIO()
                await loop.run_in_executor(
                    None,
                    lambda k=img_spec.key: s3.download_fileobj(bucket, k, buf),
                )
                jpeg_bytes = buf.getvalue()

                # Parse metadata
                meta = _parse_dji_metadata(jpeg_bytes)

                lat = meta.get("lat")
                lon = meta.get("lon")
                width = meta.get("img_width")
                height = meta.get("img_height")
                gimbal_pitch = meta.get("gimbal_pitch")
                gimbal_yaw = meta.get("gimbal_yaw")
                gimbal_roll = meta.get("gimbal_roll")
                
                # Check dewarp options
                dewarp_flag = meta.get("dewarp_flag")
                dewarp_data_str = meta.get("dewarp_data")
                should_undistort = dewarp and dewarp_flag == 0 and dewarp_data_str is not None
                
                dewarp_params = None
                if should_undistort:
                    dewarp_params = _parse_dewarp_data(dewarp_data_str)
                    if dewarp_params:
                        focal_px = dewarp_params["fx"]
                        cx = width / 2.0 + dewarp_params["cx"]
                        cy = height / 2.0 + dewarp_params["cy"]
                        print(f"[process] Applying dewarp parameters: fx={focal_px}, cx={cx}, cy={cy}")
                    else:
                        print(f"[process] Failed to parse DewarpData string: {dewarp_data_str}")
                        should_undistort = False

                if not should_undistort:
                    focal_px = meta.get("focal_px")
                    cx = meta.get("cx")
                    cy = meta.get("cy")
                    print(f"[process] No dewarping applied (dewarp={dewarp}, flag={dewarp_flag}). Using EXIF fallback: focal={focal_px}, cx={cx}, cy={cy}")

                if any(v is None for v in [lat, lon, width, height, gimbal_yaw, gimbal_pitch, gimbal_roll, focal_px]):
                    errors.append(f"{img_spec.filename}: missing required metadata — skipped")
                    state["processed"] += 1
                    continue

                # Defaults for optional fields
                if cx is None:
                    cx = width / 2.0
                if cy is None:
                    cy = height / 2.0

                agl = _estimate_agl(meta)

                # Compute ground footprint
                corners = _compute_footprint(
                    lat, lon, agl,
                    gimbal_yaw, gimbal_pitch, gimbal_roll,
                    focal_px, cx, cy, width, height,
                )

                # Write warped GeoTIFF
                tile_path = os.path.join(tmpdir, f"tile_{idx:05d}.tif")
                await loop.run_in_executor(
                    None,
                    lambda jp=jpeg_bytes, co=corners, w=width, h=height, tp=tile_path, dp=dewarp_params:
                        _warp_to_geotiff(jp, co, w, h, tp, dewarp_params=dp),
                )
                tile_paths.append(tile_path)

            except Exception as exc:
                print(f"[process] ERROR img={img_spec.filename}: {exc}")
                errors.append(f"{img_spec.filename}: {exc}")

            state["processed"] += 1
            if idx % 10 == 0 or idx < 3:
                print(f"[process] progress {state['processed']}/{len(images)} tiles_ok={len(tile_paths)}")

        if not tile_paths:
            sample = "; ".join(errors[:5])
            print(f"[process] FAILED — no tiles. Sample errors: {sample}")
            state["status"] = "failed"
            state["error"] = f"No images could be georeferenced. Errors: {sample}"
            return

        if errors:
            print(f"[process] {len(errors)} non-fatal errors, continuing with {len(tile_paths)} tiles")
            state["warnings"] = errors  # non-fatal — we still have some tiles

        # Merge into COG
        print(f"[process] merging {len(tile_paths)} tiles into COG")
        cog_path = os.path.join(tmpdir, "merged.tif")
        try:
            await loop.run_in_executor(None, _merge_to_cog, tile_paths, cog_path)
        except Exception as exc:
            print(f"[process] merge ERROR: {exc}")
            state["status"] = "failed"
            state["error"] = f"Merge failed: {exc}"
            return

        # Upload COG to S3
        output_key = f"{output_prefix.rstrip('/')}/merged.tif"
        print(f"[process] COG created, uploading to s3://{bucket}/{output_key}")
        try:
            with open(cog_path, "rb") as fh:
                await loop.run_in_executor(
                    None,
                    lambda: s3.upload_fileobj(
                        fh,
                        bucket,
                        output_key,
                        ExtraArgs={"ContentType": "image/tiff"},
                    ),
                )
        except Exception as exc:
            print(f"[process] S3 upload ERROR: {exc}")
            state["status"] = "failed"
            state["error"] = f"S3 upload failed: {exc}"
            return

        print(f"[process] COMPLETED task_id={task_id} output_key={output_key}")
        state["output_key"] = output_key
        state["status"] = "completed"


